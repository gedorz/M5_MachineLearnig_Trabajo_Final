GRANT ALL PRIVILEGES ON ALL FUNCTIONS IN SCHEMA public TO "taskpredictoruser";
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON TABLES TO "taskpredictoruser";
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON SEQUENCES TO "taskpredictoruser";
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL PRIVILEGES ON FUNCTIONS TO "taskpredictoruser";   

CREATE Table IF Not Exists tasks (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    titulo VARCHAR(255) COLLATE pg_catalog."default" NOT NULL,
    contenido TEXT COLLATE pg_catalog."default",
    completada BOOLEAN DEFAULT FALSE,
    deadline TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tasks_pkey PRIMARY KEY (id)
);

ALTER TABLE IF EXISTS public.tasks
    OWNER to "taskpredictoruser";



